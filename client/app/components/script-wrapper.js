import Component from '@glimmer/component';
import { action } from '@ember/object';
import { tracked } from '@glimmer/tracking';
import { service } from '@ember/service';
import { macroExampleByKey } from 'euclip/utils/macros/library';
import { withMacroSnippet } from 'euclip/utils/macros/schema';


export default class ScriptWrapperComponent extends Component {
  @service store;
  @tracked editorLineCount;

  // which panel is showing: the scripts, the signal-chain GUI or the presets list
  @tracked view = 'script'; // 'script' | 'signalGui' | 'presets' | 'macroMenu'
  // which script tab, when view === 'script'
  @tracked tab = 'init'; // 'init' | 'onstep' | 'macros' (the project-wide macros script)

  // the Macros menu: documented examples to load
  get showMacroMenu() {
    return this.view === 'macroMenu';
  }

  // the project-wide macros script, in the script editor's third tab
  get showMacrosScript() {
    return this.view === 'script' && this.tab === 'macros';
  }

  get showPresets() {
    return this.view === 'presets';
  }

  get showSignalGui() {
    return this.view === 'signalGui';
  }

  get showScripts() {
    return this.view === 'script';
  }

  get showInitScript() {
    return this.view === 'script' && this.tab === 'init';
  }

  get showOnstepScript() {
    return this.view === 'script' && this.tab === 'onstep';
  }

  /*
    state machine actions
  */
  @action
  openGUI() {
    this.view = 'signalGui';
  }

  @action
  openMacroMenu() {
    this.view = 'macroMenu';
  }

  @action
  openPresets() {
    this.view = 'presets';
  }

  @action
  async createScriptFromGUI(scriptModel) {
    scriptModel = await scriptModel; // convert proxy to actual model
    if (scriptModel.get('signalChainGeneratedCode')) {
      await scriptModel
        .get('updateScriptTask')
        .perform('editorContent', scriptModel.signalChainGeneratedCode);
      await scriptModel.get('runCode').perform();
    }
    this.backToScript();
  }

  @action
  backToScript() {
    this.view = 'script';
    this.tab = 'init';
  }

  @action
  setUITypeTab(selectedTab) {
    this.setTab(selectedTab);
  }

  @action
  setScriptTypeTab(selectedTab) {
    this.setTab(selectedTab);
  }

  setTab(selectedTab) {
    const tab = String(selectedTab).toLowerCase();
    // tabs only exist on the scripts panel
    if (this.view === 'script' && (tab === 'init' || tab === 'onstep' || tab === 'macros')) {
      this.tab = tab;
    }
  }

  // since the script wrapper is only rendered once on the project level
  // dynamically update the preset menu to a value saved on the track
  // when the track changes
  setDefaultPreset(presetMenu, [selectedPresetId]) {
    presetMenu.selectedPresetId = selectedPresetId;
  }

  // TODO: replace this with a global helper/util
  // for setting a property on a model record?
  @action
  updateSignalChain(scriptModel, content) {
    // signalChainGeneratedCode is a temporary property, not persisted to the database
    // used to store the code generated by the signal chain UI temporarily before saving
    // scriptModel and invoking it
    // REFACTOR: instead of saving the rendered code as signalChainGeneratedCode,
    // this could instead save the SignalChainCreator node arrays, then render them as code upon clicking Submit
    // this would allow us to save the UI state of the signal chain after a user submits it
    scriptModel
      .get('updateScriptTask')
      .perform('signalChainGeneratedCode', content);
  }

  // Loads a macro's example: its registration goes into the project's macros script (once; never duplicated),
  // and an example of using it replaces the track's setup and play scripts.
  @action
  async applyMacro(macroKey) {
    const macro = macroExampleByKey(macroKey);
    const { track, project } = this.args;
    if (!macro) throw new Error(`Unknown macro ${macroKey}`);

    // the project's macros script first: the track's setup script uses what it registers
    const macrosScript = project?.macrosScript;
    if (macrosScript) {
      const withMacro = withMacroSnippet(macrosScript.editorContent ?? '', macro);
      if (withMacro !== macrosScript.editorContent) {
        macrosScript.set('editorContent', withMacro);
        await macrosScript.runCode.perform();
      }
    }

    // the play script, then the setup script (which rebuilds the track's audio)
    if (track.onstepScript) {
      track.onstepScript.set('editorContent', macro.onstepScript);
      await track.onstepScript.runCode.perform();
    }
    track.initScript.set('editorContent', macro.initScript);
    await track.initScript.runCode.perform();
  }

  @action
  async applyPreset(presetId) {
    // save the selection on the track model so the dropdown updates when changing tracks\
    this.args.track.selectedPreset = presetId;
    // fetch the full preset record (with related script models)
    const preset = await this.store.findRecord('preset', presetId);
    await preset.applyToTrack.perform(this.args.track);
  }
}
